import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { createMemoryRouter, RouterProvider } from "react-router";
import { describe, expect, it, vi } from "vitest";
import type { UiApi } from "../api/ui";
import { BackendProvider } from "../app/BackendContext";
import { AdditionScreen } from "./AdditionScreen";

function fakeApi(overrides: Partial<UiApi> = {}): UiApi {
  return {
    getStatus: vi.fn(),
    createAddition: vi.fn().mockResolvedValue({ id: "a1", left: 3, right: 4, statement: "3 + 4" }),
    answerAddition: vi.fn(async (_id: string, answer: number) => ({ isCorrect: answer === 7, expectedAnswer: 7 })),
    readAddition: vi.fn().mockResolvedValue(new Blob()),
    ...overrides,
  };
}

function renderScreen(api: UiApi) {
  const router = createMemoryRouter([{ path: "/", element: <AdditionScreen /> }]);
  render(
    <QueryClientProvider client={new QueryClient()}>
      <BackendProvider api={api}>
        <RouterProvider router={router} />
      </BackendProvider>
    </QueryClientProvider>,
  );
}

describe("AdditionScreen", () => {
  it("shows the addition generated by the host", async () => {
    renderScreen(fakeApi());

    expect(await screen.findByText("3 + 4")).toBeInTheDocument();
    expect(screen.getByLabelText("Ta réponse")).toHaveFocus();
  });

  it("congratulates a correct answer checked by the host", async () => {
    const api = fakeApi();
    renderScreen(api);
    const user = userEvent.setup();

    await user.type(await screen.findByLabelText("Ta réponse"), "7");
    await user.click(screen.getByRole("button", { name: "Valider" }));

    expect(await screen.findByRole("status")).toHaveTextContent("Bravo !");
    expect(api.answerAddition).toHaveBeenCalledWith("a1", 7);
  });

  it("gives the right answer after a mistake", async () => {
    renderScreen(fakeApi());
    const user = userEvent.setup();

    await user.type(await screen.findByLabelText("Ta réponse"), "8{Enter}");

    expect(await screen.findByRole("status")).toHaveTextContent("La bonne réponse était 7.");
    expect(screen.getByRole("button", { name: "Nouvelle addition" })).toBeInTheDocument();
  });

  it("only accepts digits", async () => {
    renderScreen(fakeApi());
    const user = userEvent.setup();
    const input = await screen.findByLabelText("Ta réponse");

    await user.type(input, "a1b2");

    expect(input).toHaveValue("12");
  });
});
